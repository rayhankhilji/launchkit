// Generates a baseline guide for every directory that doesn't have a researched one yet,
// and rebuilds skill/launchkit/sites/INDEX.md. Researched guides (verified: true) are never touched.
import fs from 'node:fs';
import path from 'node:path';
import { loadDirectories, PKG_ROOT } from '../lib/core.mjs';

const DIR = path.join(PKG_ROOT, 'skill', 'launchkit', 'sites');
const BASE_MARK = '<!-- baseline: generated by scripts/build-guides.mjs; replace with a researched guide -->';

const CAT = {
  'Launch Platform': {
    why: 'A launch platform: listings get a day (or week) in the spotlight, so timing and the first comment matter.',
    tips: [
      'Pick the earliest free launch slot on or after the user\'s preferred launch date. Never pay to skip the queue unless the user approved it.',
      'Use `copy.maker_comment` as the first comment. Reply to every comment on launch day (tell the user).',
      'Use the best screenshot first. The thumbnail decides whether people click.',
    ],
  },
  'AI Directory': {
    why: 'An AI tools directory: people browse by category and use case, so category choice and tags drive most of the traffic.',
    tips: [
      'Choose the most specific category that fits (e.g. "Code assistant" beats "Productivity").',
      'Fill every tag and use-case field. They feed the site\'s search.',
      'Many AI directories offer a paid "featured" upgrade. Skip it at budget 0. The free listing is the goal.',
    ],
  },
  'Software Review Site': {
    why: 'A software review site: buyers compare vendors here, so a complete, accurate vendor profile matters more than clever copy.',
    tips: [
      'Create the free vendor/product profile only. Never write or solicit reviews from inside the form.',
      'Use the full `product.description_long` and list every key feature. Comparison pages pull from them.',
      'Expect a verification email or call. Mark `needs_human` if they ask for a phone call.',
    ],
  },
  'Startup Database': {
    why: 'A startup database: investors, journalists and scrapers read it, so company facts must be exact and consistent.',
    tips: [
      'Use `company.*` facts exactly as stored. Leave funding blank unless it\'s in the profile.',
      'Add the founder with `founder.name`, `founder.role` and LinkedIn so the profile links up.',
    ],
  },
  'Dev / Open Source': {
    why: 'A developer community or index: devs reward technical detail and penalise marketing tone.',
    tips: [
      'Lead with what it does technically and how to try it (repo link, install command, live demo).',
      'If the product is open source, link `product.repo_url` prominently.',
    ],
  },
  'Community': {
    why: 'A community: self-promotion is judged by tone and by whether you are a real member.',
    tips: ['Read the rules first. Draft for approval (mode post) unless the user enabled posting.'],
  },
  'Reddit': {
    why: 'A subreddit: strict self-promotion rules, and moderators remove ad-like posts fast.',
    tips: [
      'Read the sidebar rules and any self-promo day. Write a story-first post tailored to this sub.',
      'Save with `launchkit draft <id> -` and mark `drafted`. Post only if the user approved this draft.',
    ],
  },
  'Press / Media': {
    why: 'A press outlet: a short, newsworthy pitch to the right desk is the only thing that works.',
    tips: ['Use `copy.press_pitch` tailored with one outlet-specific hook. Draft it; never send email without approval.'],
  },
  'Newsletter': {
    why: 'A newsletter: editors pick a handful of tools per issue, so your one-liner has to be the hook.',
    tips: ['Submit through the free "suggest a tool" form if there is one. Sponsor slots are paid, so skip them at budget 0.'],
  },
  'Design Gallery': {
    why: 'A design gallery: only polished, visually distinctive sites get accepted.',
    tips: ['Only submit if the user\'s site is design-led. Use full-page screenshots at 1440px width.'],
  },
  'App Store / Marketplace': {
    why: 'A marketplace or store: it needs a built artifact (extension, app, plugin) plus a review process.',
    tips: ['Manual by default. Suggest it to the user only if they ship that kind of artifact.'],
  },
};
const DEFAULT = { why: 'A place to list the product.', tips: ['Fill every optional field the profile can answer. Complete listings rank higher in site search.'] };

const MODE_STEPS = {
  form: (t) => [
    `Open ${t.url}. If it's not a form, look for "Submit", "Add tool", "Get listed" or "Launch" in the header, footer or pricing page.`,
    'Search the site for `product.name` first. If a listing exists, `launchkit mark ' + t.id + ' live --listing-url <url>` and stop.',
    'Sign in if asked (preference order in docs/03). Mark `needs_human` on CAPTCHA, phone check or payment wall.',
    'Fill the fields using the field map below. Pick the copy variant whose length fits each field.',
    'Choose the free option on any pricing step. Submit, wait for the confirmation, screenshot it to `.launchkit/evidence/' + t.id + '.png`.',
    '`launchkit mark ' + t.id + ' submitted --note "<what the confirmation said>"`',
  ],
  post: (t) => [
    `Open ${t.url} and read the rules (sidebar, wiki, FAQ or guidelines).`,
    'Write a post for this specific audience from `copy.reddit_post` / `copy.launch_post_story`, following skill/human-writing.',
    '`launchkit draft ' + t.id + ' -` with title, body, flair and best posting time, then `launchkit mark ' + t.id + ' drafted`.',
    'Only if `launch_settings.allow_social_posting` is true and the user approved this draft: post it, then mark `submitted --listing-url <post url>`.',
  ],
  pitch: (t) => [
    `Open ${t.url} and find the tips/submission form or the right editor's contact.`,
    'Write a pitch from `copy.press_pitch` with one hook specific to this outlet (under 150 words, skill/human-writing).',
    '`launchkit draft ' + t.id + ' -` and mark `drafted`. Submit a web form only if `pitch` mode is enabled and the user approved it.',
  ],
  pr: (t) => [
    `Open ${t.url}, read CONTRIBUTING and the inclusion criteria.`,
    'Write the exact list line in the list\'s format (alphabetical position, description length) and save it as a draft.',
    'Open the PR only if the user approved it and GitHub access exists, then mark `submitted --listing-url <PR url>`.',
  ],
  manual: (t) => [
    `This needs a built artifact or a business process (${t.category}). Don't attempt it automatically.`,
    'If it fits the product (e.g. a browser extension for the Chrome Web Store), add it to the wrap-up as a suggestion for the user.',
  ],
};

const FIELD_MAP = `| Field on the site | Limit / format | Fill with |
|---|---|---|
| Name | text | \`product.name\` |
| URL | URL | \`product.url\` |
| Tagline / one-liner | usually 60-80 chars | \`product.tagline\` (or \`product.tagline_short\` if under 50) |
| Short description | usually 140-300 chars | \`product.description_short\` or \`product.description_medium\` |
| Long description | free text | \`product.description_long\` |
| Category / tags | select / chips | closest match to \`product.categories\`, then \`product.tags\` |
| Pricing | select | \`product.pricing_model\` (+ \`product.pricing_details\` if there's a text box) |
| Logo / icon | image | \`assets.logo_square\` |
| Screenshots | images | \`assets.screenshots\` (best first) |
| Video | URL | \`links.demo_video\` |
| Your name / email | text | \`founder.name\` / \`submission.email\` |
| Socials | URLs | \`links.twitter\`, \`links.linkedin\`, \`links.github\` |`;

function baseline(t) {
  const c = CAT[t.category] || DEFAULT;
  const steps = (MODE_STEPS[t.mode] || MODE_STEPS.form)(t).map((s, i) => `${i + 1}. ${s}`).join('\n');
  return `---
id: ${t.id}
name: ${JSON.stringify(t.name)}
url: ${t.url}
category: ${t.category}
mode: ${t.mode}
pricing: ${t.pricing}
login: unknown
captcha: unknown
backlink_required: unknown
review_time: unknown
verified: false
last_checked: ""
---
${BASE_MARK}

# ${t.name}

${c.why}${t.notes ? `\n\nNotes from the directory list: ${t.notes}` : ''}

## Steps
${steps}
${t.mode === 'form' ? `\n## Field map (generic; the real form may differ)\n\n${FIELD_MAP}\n` : ''}
## Make the listing perform
${c.tips.map((x) => `- ${x}`).join('\n')}
`;
}

const dirs = loadDirectories();
let made = 0, kept = 0;
for (const t of dirs) {
  const f = path.join(DIR, `${t.id}.md`);
  if (fs.existsSync(f) && !fs.readFileSync(f, 'utf8').includes(BASE_MARK)) { kept++; continue; }
  fs.writeFileSync(f, baseline(t));
  made++;
}

const researched = new Set(dirs.filter((t) => !fs.readFileSync(path.join(DIR, `${t.id}.md`), 'utf8').includes(BASE_MARK)).map((t) => t.id));
const byCat = {};
for (const t of dirs) (byCat[t.category] ||= []).push(t);
let idx = `# Site guides\n\nOne guide per directory. \`launchkit next\` returns the guide path for each claimed target.\n${researched.size} of ${dirs.length} guides are researched against the live site; the rest are baseline guides built from the category playbook.\n`;
for (const cat of Object.keys(byCat).sort()) {
  idx += `\n## ${cat}\n\n| Site | Mode | Pricing | Guide |\n|---|---|---|---|\n`;
  for (const t of byCat[cat].sort((a, b) => a.priority - b.priority || a.name.localeCompare(b.name))) {
    idx += `| [${t.name}](${t.url}) | ${t.mode} | ${t.pricing} | [${researched.has(t.id) ? 'researched' : 'baseline'}](${t.id}.md) |\n`;
  }
}
fs.writeFileSync(path.join(DIR, 'INDEX.md'), idx);
console.log(`guides: ${kept} researched kept, ${made} baseline written, index rebuilt`);
